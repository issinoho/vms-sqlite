#!/usr/bin/env bash
# gen_shr_opt.sh <stage> - write <stage>/vmsport/SQLITE3_SHR.OPT, the linker
# options for SQLITE3$SHR.EXE, from vmsport/sqlite3_shr.symbols.
# First compiles sqlite3.c on the host with the VMS build's options (D4) and
# checks that every exported symbol is in the list: a new release's new API
# must be appended to the list before it can be kitted.
set -euo pipefail
stage=${1:?usage: gen_shr_opt.sh <stage>}
top=$(cd "$(dirname "$0")/.." && pwd)
. "$top/upstream.conf"
list=$stage/vmsport/sqlite3_shr.symbols
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
gcc -c -O0 -w -D__VMS -DSQLITE_OS_OTHER=1 -DSQLITE_THREADSAFE=1 -DSQLITE_DEFAULT_MEMSTATUS=0 \
    -DSQLITE_OMIT_LOAD_EXTENSION -DSQLITE_MAX_MMAP_SIZE=0 -DSQLITE_ENABLE_FTS5 \
    -DSQLITE_ENABLE_RTREE -DSQLITE_ENABLE_MATH_FUNCTIONS "$stage/sqlite3.c" -o "$tmp/s.o"
nm -g --defined-only "$tmp/s.o" | awk '{print $3}' | sort > "$tmp/exports"
grep -v '^#' "$list" | awk '{print $1}' | sort > "$tmp/listed"
missing=$(comm -23 "$tmp/exports" "$tmp/listed")
[ -z "$missing" ] || { echo "gen_shr_opt: exports not in $list (append them):" $missing >&2; exit 1; }
gone=$(comm -13 "$tmp/exports" "$tmp/listed")
[ -z "$gone" ] || { echo "gen_shr_opt: listed but no longer exported:" $gone >&2; exit 1; }
IFS=. read -r major minor _ <<< "$UPSTREAM_VERSION"
{
    echo "! SQLITE3\$SHR.EXE: generated by tools/gen_shr_opt.sh from sqlite3_shr.symbols"
    echo "GSMATCH=LEQUAL,$major,$minor"
    echo "CASE_SENSITIVE=YES"
    n=$(grep -vc '^#' "$list")
    i=0
    grep -v '^#' "$list" | while read -r name kind; do
        i=$((i + 1))
        t=PROCEDURE; [ "${kind:-}" = DATA ] && t=DATA
        if [ $i -eq 1 ]; then pre="SYMBOL_VECTOR=("; else pre="    "; fi
        if [ $i -eq "$n" ]; then post=")"; else post=",-"; fi
        echo "$pre$name=$t$post"
    done
    echo "CASE_SENSITIVE=NO"
} > "$stage/vmsport/SQLITE3_SHR.OPT"
echo "gen_shr_opt: $(grep -vc '^#' "$list") symbols, GSMATCH=LEQUAL,$major,$minor"
